#1 Write a program to demonstrate conditional statements using if if-else and if-elif-else.

#if
age=20

if age>=18:
    print("Adult")

#if else

n=20

if n%2==0:
    print("Odd")
else:
    print("Even")

#if elif else

mark=75

if mark>=90:
    print("Grade : A")
elif mark>=70:
    print("Grade : B")
elif mark>=60:
    print("Grade : C")
else:
    print("Fail")
