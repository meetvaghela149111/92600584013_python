import math

n = 25

print("absolute value =",math.fabs(-10))
print("square root =",math.sqrt(n))
print("power =",math.pow(3, 2))
print("logarithm =",math.log10(100))
print("sine =",math.sin(math.radians(30)))
print("cosine =",math.cos(math.radians(60)))
print("ceiling =",math.ceil(5.3))
print("floor =",math.floor(5.9))
print("pi value =",math.pi)
print("gcd =",math.gcd(15, 10))
